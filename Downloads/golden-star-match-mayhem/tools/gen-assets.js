// Regenerates src/js/00-assets.js from the image files in /assets.
// Usage: node tools/gen-assets.js   (run after replacing any sprite/art file)
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const b64 = f => "data:image/webp;base64," + fs.readFileSync(f).toString("base64");
const sp = {};
for (const f of fs.readdirSync(path.join(root, "assets/sprites")).sort())
  if (f.endsWith(".webp")) sp[f.replace(".webp", "")] = b64(path.join(root, "assets/sprites", f));
const piece = k => b64(path.join(root, "assets/intro/piece-" + k + ".webp"));
let out = "// 00-assets.js - GENERATED by tools/gen-assets.js. Do not edit by hand.\n";
out += "const SP={" + Object.entries(sp).map(([k, v]) => k + ':"' + v + '"').join(",") + "};\n";
out += "SP.gs_idle=SP.gs_i0;SP.gs_dash=SP.gs_arc;SP.g1=SP.g1_i0;SP.g2=SP.g2_i0;SP.g3=SP.g3_i0;SP.b=SP.b_i0;\n";
out += 'const ART="' + b64(path.join(root, "assets/art/menu-art.webp")) + '";\n';
out += "const IMGS=[" + ["S", "J", "T"].map(k => '"' + piece(k) + '"').join(",") + '],MASK="' + b64(path.join(root, "assets/intro/vc-mark-mask.webp")) + '";\n';
fs.writeFileSync(path.join(root, "src/js/00-assets.js"), out);
console.log("00-assets.js regenerated:", Object.keys(sp).length, "sprites");
